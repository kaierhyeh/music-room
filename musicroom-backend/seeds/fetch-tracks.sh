#!/usr/bin/env bash
set -euo pipefail

API="${DEEZER_API_BASE:-https://api.deezer.com}"

QUERIES=(
  'Daft Punk Around the World'
  'Daft Punk One More Time'
  'Justice D.A.N.C.E.'
  'LCD Soundsystem Dance Yrself Clean'
  'Moderat A New Error'
  'Bonobo Kerala'
  'Caribou Odessa'
  'Four Tet Baby'
  'Radiohead Weird Fishes Arpeggi'
  'Portishead Glory Box'
  'Massive Attack Teardrop'
  'Air La Femme d'"'"'Argent'
  'Nina Simone Feeling Good'
  'John Coltrane Naima'
  'Miles Davis So What'
  'Kendrick Lamar Money Trees'
  'A Tribe Called Quest Can I Kick It'
  'Fela Kuti Water No Get Enemy'
  'Tame Impala Let It Happen'
  'Khruangbin August 10'
)

FILTER='  def sql: if . == null then "NULL" else $q + (tostring | gsub($q; $q + $q)) + $q end;
  def num: if . == null then "NULL" else tostring end;
  "  (" + (.id|num) + ", " + (.title|sql) + ", " + (.artist.name|sql) + ", "
       + (.album.title|sql) + ", " + (.duration|num) + ", "
       + (.preview|sql) + ", " + (.album.cover_big|sql) + ")"
'

cat <<'HEADER'
-- seeds/tracks.sql -- GENERATED by seeds/fetch-tracks.sh, do not edit by hand.
--
-- Deezer metadata cache. Upserts, so re-running after a regeneration refreshes
-- the signed (and short-lived) preview URLs in place. Apply before seed.sql:
-- playlist_tracks and event_tracks both carry a FK to tracks(deezer_id).

BEGIN;

INSERT INTO tracks (deezer_id, title, artist_name, album_title, duration_sec, preview_url, cover_url) VALUES
HEADER

first=1
for query in "${QUERIES[@]}"; do
  row=$(curl -sG --max-time 20 "$API/search" \
          --data-urlencode "q=$query" --data-urlencode 'limit=1' \
        | jq -c '.data[0] // empty')
  if [ -z "$row" ]; then
    echo "warning: no Deezer result for: $query" >&2
    continue
  fi
  [ "$first" -eq 1 ] || printf ',\n'
  first=0
  printf '%s' "$row" | jq -rj --arg q "'" "$FILTER"
done
printf '\n'

cat <<'FOOTER'
ON CONFLICT (deezer_id) DO UPDATE SET
    title        = EXCLUDED.title,
    artist_name  = EXCLUDED.artist_name,
    album_title  = EXCLUDED.album_title,
    duration_sec = EXCLUDED.duration_sec,
    preview_url  = EXCLUDED.preview_url,
    cover_url    = EXCLUDED.cover_url,
    cached_at    = now();

COMMIT;
FOOTER
