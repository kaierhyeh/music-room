\if :{?users}
\else
  \set users 500
\endif

BEGIN;

CREATE TEMP TABLE bulk_hash ON COMMIT DROP AS
SELECT crypt('Password123!', gen_salt('bf', 12)) AS h;

INSERT INTO users (email, password_hash, email_verified, display_name,
                   profile_data, music_preferences)
SELECT
    'load-' || n || '@musicroom.bulk',
    (SELECT h FROM bulk_hash),
    true,
    (ARRAY['Ana','Bruno','Chloe','Diego','Elsa','Farid','Gaia','Hugo',
           'Iris','Jonas','Kenza','Liam','Maya','Noe','Olga','Pablo'])[1 + (n * 7) % 16]
      || ' ' ||
    (ARRAY['Bernard','Costa','Dubois','Eriksen','Ferrari','Garcia','Haddad',
           'Ibrahim','Jensen','Kowalski'])[1 + (n * 3) % 10],
    jsonb_build_object('bio', 'Load test account #' || n, 'location', 'Paris'),
    jsonb_build_object(
        'genres', to_jsonb(ARRAY[(ARRAY['electronic','jazz','hip-hop','rock','ambient'])[1 + n % 5]]),
        'artists', '[]'::jsonb)
FROM generate_series(1, :users) AS n
ON CONFLICT (email) DO NOTHING;

WITH newcomers AS (
    SELECT u.id
    FROM users u
    WHERE u.email LIKE 'load-%@musicroom.bulk'
      AND NOT EXISTS (SELECT 1 FROM playlists p WHERE p.owner_id = u.id)
),
ins AS (
    INSERT INTO playlists (owner_id, name, description, visibility, license)
    SELECT id, 'Load Test Playlist', 'Generated by seed-bulk.sql.', 'public', 'open'
    FROM newcomers
    RETURNING id, owner_id
)
INSERT INTO playlist_tracks (playlist_id, track_deezer_id, position, added_by)
SELECT ins.id, t.deezer_id,
       row_number() OVER (PARTITION BY ins.id ORDER BY t.deezer_id) * 1024.0,
       ins.owner_id
FROM ins
CROSS JOIN LATERAL (
    SELECT deezer_id FROM tracks ORDER BY deezer_id LIMIT 8
) t;

COMMIT;

ANALYZE users;
ANALYZE playlists;
ANALYZE playlist_tracks;
